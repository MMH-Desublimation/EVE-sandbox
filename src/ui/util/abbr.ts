/** 归属于“武器”的分组（含发射器/炮/激光等）；命中则直接返回 weaponAbbr 的具体型号简写。 */
const WEAPON_GROUP_RE = /武器|发射器|激光|投射器|炮台|炮\b/;

/* ------------------------------------------------------------------ 主函数 */

/** 规则来源，便于自检统计“退化比例”。 */
export type AbbrSource = "resistance" | "group" | "weapon" | "fallback";

export interface AbbrResult {
  abbr: string;
  source: AbbrSource;
}

/**
 * 中文简写（附带命中来源，供自检使用）。
 * 顺序：抗性 → 分组规则 → 武器型号 → 通用退化。
 */
export function moduleAbbrDetailed(zhName: string, groupName = ""): AbbrResult {
  const zh = String(zhName ?? "").trim();
  const group = String(groupName ?? "").trim();

  if (!zh && !group) return { abbr: "?", source: "fallback" };

  // 1) 抗性类：需同时具备「层级」与「抗性类型」，且不能是维修/回充类。
  if (!REPAIRISH_RE.test(zh)) {
    const layer = detectLayer(zh, group);
    const resType = detectResType(zh);
    if (layer && resType) return { abbr: layer + resType, source: "resistance" };
  }

  // 2) 分组规则（首个命中即返回）。
  for (const [re, abbr] of GROUP_RULES) {
    if (re.test(group)) return { abbr, source: "group" };
  }

  // 3) 武器 → 具体型号简写。
  if (WEAPON_GROUP_RE.test(group)) {
    const w = weaponAbbr(zh || group);
    if (w) return { abbr: w, source: "weapon" };
  }

  // 4) 退化：去掉科技等级后缀，最多取前 6 字；绝不返回空串。
  const base = stripTech(zh) || group || zh;
  return { abbr: truncate(base, 6) || "?", source: "fallback" };
}

/**
 * 模块中文简写（显示用，不影响引擎语义）。
 * @param zhName 中文名，如 `多谱式护盾增强器 II`
 * @param groupName 中文分组名（可选），如 `护盾强化设备`
 */
export function moduleAbbr(zhName: string, groupName = ""): string {
  return moduleAbbrDetailed(zhName, groupName).abbr;
}

/**
 * 武器中文简写：去掉尾部科技等级，保留型号数字（`1400mm榴弹炮 II` → `1400mm榴弹炮`）。
 * 过长则截断到 10 字以内，保留开头的尺寸/口径数字。
 */
export function weaponAbbr(zhName: string): string {
  const base = stripTech(zhName);
  if (!base) return "";
  return truncate(base, 10);
}

/* ------------------------------------------------------------------ 工具 */

/** 去掉科技等级后缀：尾部 ` I` / ` II` / ` III`（允许无空格，如 `电磁护盾增效器I`）。 */
export function stripTech(zhName: string): string {
  return String(zhName ?? "")
    .replace(/\s*(?:I{1,3}|IV|V|VI)$/u, "")
    .trim();
}

/** 截断到 n 个字符（保留开头，从而保留 `1400mm` 这类尺寸/口径前缀）。 */
function truncate(s: string, n: number): string {
  return s.length > n ? s.slice(0, n) : s;
}

/* ------------------------------------------------------------------ 抗性类规则 */

/** 抗性层级：名称或分组含 护盾→盾 / 装甲→甲 / 结构|船体→构。 */
function detectLayer(zh: string, groupName: string): string {
  const s = zh + "|" + (groupName || "");
  if (/护盾/.test(s)) return "盾";
  if (/装甲/.test(s)) return "甲";
  if (/结构|船体/.test(s)) return "构";
  return "";
}

/**
 * 抗性类型关键词。
 * 注意顺序：多谱式/适应（全抗）优先，其余按 爆/动/热/电 单属性。
 * 数据核对：`爆炸涂层/动能护盾增效器/热能装甲增强器/电磁护盾增效器` 等均命中。
 */
function detectResType(zh: string): string {
  if (/多谱式|适应/.test(zh)) return "全抗";
  if (/爆炸/.test(zh)) return "爆抗";
  if (/动能/.test(zh)) return "动抗";
  if (/热能/.test(zh)) return "热抗";
  if (/电磁|EM/i.test(zh)) return "电抗";
  return "";
}

